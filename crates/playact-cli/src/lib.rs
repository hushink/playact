/// Runs the command line and returns the process exit code.
#[must_use]
pub fn main_entry() -> ExitCode {
    let mut arguments = env::args_os().skip(1);
    let Some(command) = arguments.next() else {
        eprintln!("{USAGE}");
        return ExitCode::FAILURE;
    };
    let arguments: Vec<OsString> = arguments.collect();

    let outcome = match command.to_str() {
        Some("schema") => run_schema(arguments),
        Some("catalog") => run_catalog(arguments),
        Some("lint") => run_lint(arguments),
        Some("convert") => run_convert(arguments),
        Some("bundle") => run_bundle(arguments),
        Some("graph") => run_graph(arguments),
        Some("fmt") => run_fmt(arguments),
        Some("check") => run_check(arguments),
        Some("migrate") => run_migrate(arguments),
        Some("diff") => run_diff(arguments),
        Some("-h" | "--help" | "help") => {
            println!("{USAGE}");
            return ExitCode::SUCCESS;
        }
        Some(other) => Err(format!("unknown command `{other}`").into()),
        None => Err(String::from("command must be valid UTF-8").into()),
    };

    match outcome {
        Ok(Outcome::Success) => ExitCode::SUCCESS,
        Ok(Outcome::Invalid) => ExitCode::FAILURE,
        Err(error) => {
            eprintln!("playact: {error}");
            ExitCode::FAILURE
        }
    }
}

fn run_schema(arguments: Vec<OsString>) -> Result<Outcome, Box<dyn Error>> {
    let mut output = None;
    let mut arguments = arguments.into_iter();
    while let Some(argument) = arguments.next() {
        match argument.to_str() {
            Some("-h" | "--help") => {
                println!("{SCHEMA_USAGE}");
                return Ok(Outcome::Success);
            }
            Some("-o" | "--output") => {
                output = Some(next_path(&mut arguments, "--output")?);
            }
            Some(option) if option.starts_with('-') => {
                return Err(format!("unknown option `{option}`").into());
            }
            _ => return Err(String::from("schema accepts no positional arguments").into()),
        }
    }

    let schema = TreeSpec::json_schema();
    let json = serde_json::to_vec_pretty(&schema)?;
    write_output(output.as_deref(), &json)?;
    Ok(Outcome::Success)
}

