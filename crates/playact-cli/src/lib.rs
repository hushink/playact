//! Schema, catalog, and lint tools for playact behavior trees.
//!
//! The `playact` binary exposes:
//!
//! - `schema`: write the base `TreeSpec` JSON Schema;
//! - `catalog`: render node types and registered names from a schema;
//! - `lint`: validate JSON, TOML, YAML, or RON configurations, including
//!   recursively resolved includes;
//! - `convert`: validate and rewrite a configuration in another format,
//!   optionally converting its include graph into a directory;
//! - `bundle`: validate a configuration and copy its include graph into an
//!   empty output directory;
//! - `graph`: render node structure and include relationships as Mermaid or DOT;
//! - `fmt`: validate and rewrite configurations in canonical form, optionally
//!   across the entire include graph;
//! - `check`: validate configurations and verify canonical formatting without
//!   writing;
//! - `migrate`: apply declarative version migrations from a manifest;
//! - `diff`: compare node structure, parameters, and include file sets.
//!
//! Registry-aware schemas produced by `NodeRegistry::json_schema()` can be
//! passed to `catalog`, `lint`, `convert`, `bundle`, `fmt`, and `diff` with
//! `--schema`.

mod bundle;
mod catalog;
mod convert;
mod diff;
