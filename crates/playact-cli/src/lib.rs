//! Schema, catalog, and lint tools for playact behavior trees.
//!
//! The `playact` binary exposes:
//!
//! - `schema`: write the base `TreeSpec` JSON Schema;
//! - `catalog`: render node types and registered names from a schema;
//! - `lint`: validate JSON, TOML, YAML, or RON configurations against a schema.
//!
//! Registry-aware schemas produced by `NodeRegistry::json_schema()` can be
//! passed to `catalog` and `lint` with `--schema`.

mod catalog;
mod format;
mod lint;

use std::env;
use std::error::Error;
use std::ffi::OsString;
use std::fs;
use std::io::Write;
use std::path::{Path, PathBuf};
use std::process::ExitCode;

use playact::config::TreeSpec;
use serde_json::Value;

pub use lint::{LintIssue, LintReport};

/// Top-level command help.
pub const USAGE: &str = "\
usage: playact <COMMAND> [OPTIONS]

Commands:
  schema   Write the base TreeSpec JSON Schema
  catalog  Render node types and registered names as Markdown
  lint     Validate configurations against a TreeSpec schema

Run `playact <COMMAND> --help` for command options.";

const SCHEMA_USAGE: &str = "usage: playact schema [--output PATH]";
const CATALOG_USAGE: &str = "\
usage: playact catalog [--schema PATH] [--output PATH]

Without --schema, the base TreeSpec schema is used. Pass a registry-aware
schema generated by NodeRegistry::json_schema() to include registered names.";
const LINT_USAGE: &str = "\
usage: playact lint [--schema PATH] [--json] CONFIG...

The format is selected by extension: .json, .toml, .yaml/.yml, or .ron.
Without --schema, the base TreeSpec schema is used. Pass a registry-aware
schema generated by NodeRegistry::json_schema() to validate registered names
and parameter schemas.";

enum Outcome {
    Success,
    Invalid,
}

/// Runs the command line and returns the process exit code.
#[must_use]
pub fn main_entry() -> ExitCode {
    let mut arguments = env::args_os().skip(1);
    let Some(command) = arguments.next() else {
        eprintln!("{USAGE}");
        return ExitCode::FAILURE;
    };
    let arguments: Vec<OsString> = arguments.collect();

    let outcome = match command.to_str() {
        Some("schema") => run_schema(arguments),
        Some("catalog") => run_catalog(arguments),
        Some("lint") => run_lint(arguments),
        Some("-h" | "--help" | "help") => {
            println!("{USAGE}");
            return ExitCode::SUCCESS;
        }
        Some(other) => Err(format!("unknown command `{other}`").into()),
        None => Err(String::from("command must be valid UTF-8").into()),
    };

    match outcome {
        Ok(Outcome::Success) => ExitCode::SUCCESS,
        Ok(Outcome::Invalid) => ExitCode::FAILURE,
        Err(error) => {
            eprintln!("playact: {error}");
            ExitCode::FAILURE
        }
    }
}

fn run_schema(arguments: Vec<OsString>) -> Result<Outcome, Box<dyn Error>> {
    let mut output = None;
    let mut arguments = arguments.into_iter();
    while let Some(argument) = arguments.next() {
        match argument.to_str() {
            Some("-h" | "--help") => {
                println!("{SCHEMA_USAGE}");
                return Ok(Outcome::Success);
            }
            Some("-o" | "--output") => {
                output = Some(next_path(&mut arguments, "--output")?);
            }
            Some(option) if option.starts_with('-') => {
                return Err(format!("unknown option `{option}`").into());
            }
            _ => return Err(String::from("schema accepts no positional arguments").into()),
        }
    }

    let schema = TreeSpec::json_schema();
    let json = serde_json::to_vec_pretty(&schema)?;
    write_output(output.as_deref(), &json)?;
    Ok(Outcome::Success)
}

fn run_catalog(arguments: Vec<OsString>) -> Result<Outcome, Box<dyn Error>> {
    let mut schema_path = None;
    let mut output = None;
    let mut arguments = arguments.into_iter();
    while let Some(argument) = arguments.next() {
        match argument.to_str() {
            Some("-h" | "--help") => {
                println!("{CATALOG_USAGE}");
                return Ok(Outcome::Success);
            }
            Some("-s" | "--schema") => {
                schema_path = Some(next_path(&mut arguments, "--schema")?);
            }
            Some("-o" | "--output") => {
                output = Some(next_path(&mut arguments, "--output")?);
            }
            Some(option) if option.starts_with('-') => {
                return Err(format!("unknown option `{option}`").into());
            }
            _ => return Err(String::from("catalog accepts no positional arguments").into()),
        }
    }

    let schema = load_schema(schema_path.as_deref())?;
    let markdown = catalog::render(&schema);
    write_output(output.as_deref(), markdown.as_bytes())?;
    Ok(Outcome::Success)
}

fn run_lint(arguments: Vec<OsString>) -> Result<Outcome, Box<dyn Error>> {
    let mut schema_path = None;
    let mut json_output = false;
    let mut options_done = false;
    let mut files = Vec::new();
    let mut arguments = arguments.into_iter();

    while let Some(argument) = arguments.next() {
        if !options_done {
            match argument.to_str() {
                Some("-h" | "--help") => {
                    println!("{LINT_USAGE}");
                    return Ok(Outcome::Success);
                }
                Some("--json") => {
                    json_output = true;
                    continue;
                }
                Some("-s" | "--schema") => {
                    schema_path = Some(next_path(&mut arguments, "--schema")?);
                    continue;
                }
                Some("--") => {
                    options_done = true;
                    continue;
                }
                Some(option) if option.starts_with('-') => {
                    return Err(format!("unknown option `{option}`").into());
                }
                _ => {}
            }
        }
        files.push(PathBuf::from(argument));
    }
    if files.is_empty() {
        return Err(String::from("lint requires at least one configuration path").into());
    }

    let schema = load_schema(schema_path.as_deref())?;
    jsonschema::validator_for(&schema).map_err(|error| format!("invalid schema: {error}"))?;
    let reports = lint::lint_files(&schema, &files);
    let invalid = reports.iter().filter(|report| !report.valid).count();

    if json_output {
        println!("{}", serde_json::to_string_pretty(&reports)?);
    } else {
        for report in &reports {
            if report.valid {
                println!("{}: valid", report.file);
            } else {
                eprintln!("{}:", report.file);
                for issue in &report.issues {
                    eprintln!(
                        "  {} error at `{}`: {}",
                        issue.source, issue.path, issue.message
                    );
                }
            }
        }
        if invalid > 0 && reports.len() > 1 {
            eprintln!("{} of {} configuration(s) invalid", invalid, reports.len());
        }
    }

    Ok(if invalid == 0 {
        Outcome::Success
    } else {
        Outcome::Invalid
    })
}

fn load_schema(path: Option<&Path>) -> Result<Value, Box<dyn Error>> {
    match path {
        Some(path) => {
            let text = fs::read_to_string(path)?;
            Ok(serde_json::from_str(&text)?)
        }
        None => Ok(TreeSpec::json_schema()),
    }
}

fn next_path(
    arguments: &mut impl Iterator<Item = OsString>,
    option: &str,
) -> Result<PathBuf, Box<dyn Error>> {
    arguments
        .next()
        .map(PathBuf::from)
        .ok_or_else(|| format!("{option} requires a path").into())
}

fn write_output(path: Option<&Path>, contents: &[u8]) -> Result<(), Box<dyn Error>> {
    match path {
        Some(path) => {
            if let Some(parent) = path.parent().filter(|path| !path.as_os_str().is_empty()) {
                fs::create_dir_all(parent)?;
            }
            fs::write(path, contents)?;
        }
        None => {
            let mut stdout = std::io::stdout().lock();
            stdout.write_all(contents)?;
            stdout.write_all(b"\n")?;
        }
    }
    Ok(())
}
