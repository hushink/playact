fn run_lint(arguments: Vec<OsString>) -> Result<Outcome, Box<dyn Error>> {
    let mut schema_path = None;
    let mut include_base = None;
    let mut json_output = false;
    let mut watch = false;
    let mut options_done = false;
    let mut files = Vec::new();
    let mut arguments = arguments.into_iter();

    while let Some(argument) = arguments.next() {
        if !options_done {
            match argument.to_str() {
                Some("-h" | "--help") => {
                    println!("{LINT_USAGE}");
                    return Ok(Outcome::Success);
                }
                Some("--json") => {
                    json_output = true;
                    continue;
                }
                Some("--watch") => {
                    watch = true;
                    continue;
                }
                Some("-s" | "--schema") => {
                    schema_path = Some(next_path(&mut arguments, "--schema")?);
                    continue;
                }
                Some("-b" | "--include-base") => {
                    include_base = Some(next_path(&mut arguments, "--include-base")?);
                    continue;
                }
                Some("--") => {
                    options_done = true;
                    continue;
                }
                Some(option) if option.starts_with('-') => {
                    return Err(format!("unknown option `{option}`").into());
                }
                _ => {}
            }
        }
        files.push(PathBuf::from(argument));
    }
    if files.is_empty() {
        return Err(String::from("lint requires at least one configuration path").into());
    }
    if watch && json_output {
        return Err(String::from("--watch cannot be combined with --json").into());
    }

    let schema = load_schema(schema_path.as_deref())?;
    jsonschema::validator_for(&schema).map_err(|error| format!("invalid schema: {error}"))?;

    if watch {
        return watch_loop(schema_path.as_deref(), &files, include_base.as_deref());
    }

    let reports = lint::lint_files(&schema, &files, include_base.as_deref());
    let invalid = reports.iter().filter(|report| !report.valid).count();
    if json_output {
        println!("{}", serde_json::to_string_pretty(&reports)?);
    } else {
        print_human_reports(&reports);
    }

    Ok(if invalid == 0 {
        Outcome::Success
    } else {
        Outcome::Invalid
    })
}

fn run_convert(arguments: Vec<OsString>) -> Result<Outcome, Box<dyn Error>> {
    let mut schema_path = None;
    let mut include_base = None;
    let mut recursive = false;
    let mut target_format = None;
    let mut options_done = false;
    let mut paths = Vec::new();
    let mut arguments = arguments.into_iter();

    while let Some(argument) = arguments.next() {
        if !options_done {
            match argument.to_str() {
                Some("-h" | "--help") => {
                    println!("{CONVERT_USAGE}");
                    return Ok(Outcome::Success);
                }
                Some("-r" | "--recursive") => {
                    recursive = true;
                    continue;
                }
                Some("-f" | "--format") => {
                    let value = arguments
                        .next()
                        .ok_or("--format requires a value")?
                        .into_string()
                        .map_err(|_| "--format must be valid UTF-8")?;
                    target_format = Some(format::Format::from_name(&value)?);
                    continue;
                }
                Some("-s" | "--schema") => {
                    schema_path = Some(next_path(&mut arguments, "--schema")?);
                    continue;
                }
                Some("-b" | "--include-base") => {
                    include_base = Some(next_path(&mut arguments, "--include-base")?);
                    continue;
                }
                Some("--") => {
                    options_done = true;
                    continue;
                }
                Some(option) if option.starts_with('-') => {
                    return Err(format!("unknown option `{option}`").into());
                }
                _ => {}
            }
        }
        paths.push(PathBuf::from(argument));
    }
    if paths.len() != 2 {
        return Err(String::from("convert requires INPUT and OUTPUT paths").into());
    }
    let input = &paths[0];
    let output = &paths[1];
    if input == output {
        return Err(String::from("input and output paths must differ").into());
    }
    if !recursive && target_format.is_some() {
        return Err(String::from("--format is only valid with --recursive").into());
    }

    let input_format = format::Format::from_path(input)?;
    let schema = load_schema(schema_path.as_deref())?;
    jsonschema::validator_for(&schema).map_err(|error| format!("invalid schema: {error}"))?;

    let report = lint::lint_file(&schema, input, include_base.as_deref());
    if !report.valid {
        print_human_reports(std::slice::from_ref(&report));
        return Ok(Outcome::Invalid);
    }

    if recursive {
        let target = target_format.ok_or(String::from(
            "convert --recursive requires --format json, toml, yaml, or ron",
        ))?;
        let outcome = convert::convert_recursive(
            input,
            output,
            target,
            &report.included,
            include_base.as_deref(),
        )?;
        println!(
            "converted {} file(s) from {} to {} (root {})",
            outcome.files,
            lint::display_path(input),
            lint::display_path(output),
            lint::display_path(&outcome.root),
        );
        return Ok(Outcome::Success);
    }

    let output_format = format::Format::from_path(output)?;
    let text = fs::read_to_string(input)?;
    let spec = input_format.parse_spec(&text)?;
    let output_bytes = output_format.serialize_spec(&spec)?;
    write_output(Some(&paths[1]), &output_bytes)?;
    println!("converted {} -> {}", paths[0].display(), paths[1].display());
    Ok(Outcome::Success)
}

